unsigned char CharToHex(unsigned char in)
{
	unsigned char out=100;
	if(in >= '0' && in <= '9')
	out = in - '0';
	else if(in >= 'A' && in <= 'F')
	out = in - 'A' + 10;
	else if(in >= 'a' && in <= 'f')
	out = in - 'a' + 10;
	if(out != 100)
	return out;
	else return ERR_IN_CHG;
}
