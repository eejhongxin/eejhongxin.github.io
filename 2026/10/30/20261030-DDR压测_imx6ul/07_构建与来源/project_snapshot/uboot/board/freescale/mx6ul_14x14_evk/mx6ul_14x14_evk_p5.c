unsigned int CharToDec(unsigned char *in)
{
	unsigned int i=0,size;
//	unsigned int num[20];
	unsigned int out = 0;
//	memset(num, 0, sizeof(num));
	size = sizeof(in);
	//printf("IN chartodec:size=%d\n",size);
	for(i=0; i < size; i++)
	{
		//printf("IN chartodec:in[%d]=%c\n",i,in[i]);
		if(in[i] == '\0')	break;
		else if(in[i] >= '0' && in[i] <= '9')
		out = (in[i]-'0')+16*out; 
		else if(in[i] >= 'a' && in[i] <= 'f')
		out = (in[i]-'a'+10)+16*out; 
	}
	//printf("IN chartodec:out=%d\n",out);
	return out;
}
